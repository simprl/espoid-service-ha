export const dictionaries = { en, uk, ru: uk };
export function locale(language = "en") {
    const base = language.toLowerCase().split(/[-_]/)[0];
    return base === "uk" || base === "ru" ? base : "en";
}
export function translate(language, key, values = {}) {
    return dictionaries[locale(language)][key].replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}
